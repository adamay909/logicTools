package gentzen

import (
	"strings"

	"github.com/adamay909/logicTools/ju"
)

type tablNodeVal struct {
	tkstr     tokenStr
	str       string
	processed bool
	//closed    bool
	//visited   bool
	//full      bool
}

const (
	visitedtblNode int = iota
	closedtblNode
	fulltblNode
)

type tablNode = ju.Node[tablNodeVal]

func generateTableau(s string, closeOff bool) *tablNode {

	tk, err := tokenize(s, !allowGreekUpper, !allowSpecial)

	if err != nil {
		panic("not a wff")
	}

	n := newtablnode(tk)

	done := false

	for nl := n.Linearize(); !done; nl = n.Linearize() {

		done = true

		for _, e := range nl {
			if !e.HasFlag(visitedtblNode) && !e.HasFlag(closedtblNode) {
				done = false
			}
			growTree(e, closeOff)
		}
	}

	return n
}

func generateNormalTableau(s string) *tablNode {

	return generateTableau(s, true)

}

func generateFullTableau(s string) *tablNode {

	return generateTableau(s, false)
}

func isTautologyTableau(s string) bool {

	return !isConsistent("N" + s)

}

func isConsistent(s string) bool {

	n := generateNormalTableau(s)

	v := false

	ingressFunc := func(e *tablNode) {

		if v {
			return
		}

		if len(e.Children()) != 0 {
			return
		}

		if !e.HasFlag(closedtblNode) {
			v = true
		}
	}

	n.Root().Walk(ingressFunc, func(*tablNode) {}, func(*tablNode) {})

	return v
}

func checkIfClosed(n *tablNode) {

	target := n.Val.tkstr.negate().String()

	for c := n.Parent(); c != nil; c = c.Parent() {
		if c.Val.str == target {
			n.SetFlag(closedtblNode)
			return
		}
	}

	if n.Val.tkstr[0].tokenType == tNeg {
		target = n.Val.tkstr[1:].String()

		for c := n.Parent(); c != nil; c = c.Parent() {
			if c.Val.str == target {
				n.SetFlag(closedtblNode)
				return
			}
		}
	}
	return
}

func newtablnode(tk tokenStr) *tablNode {

	var v tablNodeVal

	v.tkstr = make(tokenStr, 0, len(tk))

	v.tkstr = append(v.tkstr, tk...)

	v.str = v.tkstr.String()

	n := new(tablNode)

	n.Val = v

	return n
}

// return value open indicates that at least one subbranch is not closed
func growTree(n *tablNode, closeOff bool) {

	if n.HasFlag(closedtblNode) {
		n.SetFlag(visitedtblNode)
	}

	if n.HasFlag(visitedtblNode) {
		return
	}

	n.SetFlag(visitedtblNode)

	subs := n.Val.tkstr.subFormulas()

	switch n.Val.tkstr[0].tokenType {

	case tConj:

		addChild(n, closeOff, subs[0])
		addChild(n, closeOff, subs[1])

	case tDisj:

		addChild(n, closeOff, subs[0], subs[1])

	case tCond:

		addChild(n, closeOff, subs[0].negate(), subs[1])

	case tNeg:

		switch n.Val.tkstr[1].tokenType {

		case tNeg:

			addChild(n, closeOff, n.Val.tkstr[2:])

			//NKpq => ANpNq
		case tConj:

			subs2 := subs[0].subFormulas()

			addChild(n, closeOff, subs2[0].negate(), subs2[1].negate())

			//NApq => KNpNq
		case tDisj:

			subs2 := subs[0].subFormulas()

			addChild(n, closeOff, subs2[0].negate())
			addChild(n, closeOff, subs2[1].negate())

			//NCpq =>KpNq
		case tCond:

			subs2 := subs[0].subFormulas()

			addChild(n, closeOff, subs2[0])
			addChild(n, closeOff, subs2[1].negate())

		}
	default:
		n.SetFlag(fulltblNode)
	}
}

func addChild(n *tablNode, closeOff bool, c ...tokenStr) {

	gp := n.Linearize()

	for _, e := range gp {
		if len(e.Children()) != 0 {
			continue
		}
		if e.HasFlag(closedtblNode) {
			continue
		}
		for _, ch := range c {
			nc := newtablnode(ch)
			e.AddChild(nc)
			if closeOff {
				checkIfClosed(nc)
			}
		}
	}
}

// PrintSemanticTableau returns the LaTeX code for printing the
// semantic tableau of s in tree form. A closed branch terminates
// with a circle with an x inside.
func PrintSemanticTableau(s string) string {

	t := generateTableau(s, true)

	return printTableau(t)
}

func printFullTableau(s string) string {

	t := generateTableau(s, false)

	return printTableau(t)

}

func printTableau(t *tablNode) string {

	w := new(strings.Builder)

	ingressFunc := func(n *tablNode) {

		w.WriteString(`[ \p{`)
		w.WriteString(StringF(Parse(n.Val.str, !allowGreekUpper), O_Latex))
		w.WriteString(`} `)
		w.WriteString("\n")

		if n.HasFlag(closedtblNode) {
			w.WriteString(`[ \p{\otimes} ]`)
			w.WriteString("\n")
			w.WriteString(` ] `)
			w.WriteString("\n")
			return
		}
	}

	pivotFunc := func(m *tablNode) {

		w.WriteString(` ] `)
		w.WriteString("\n")
	}

	egressFunc := func(m *tablNode) {

		if !m.IsLastSibling() {
			return
		}

		w.WriteString(` ] `)
		w.WriteString("\n")
	}

	w.WriteString(`\begin{forest}` + "\n")
	w.WriteString(`%semantic tableau of:` + "\n% " + t.Root().Val.str + "\n")
	w.WriteString(`%generated by gentzen` + "\n")

	t.Walk(ingressFunc, pivotFunc, egressFunc)

	w.WriteString(`\end{forest}` + "\n\n")

	return w.String()

}
